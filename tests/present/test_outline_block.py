#!/usr/bin/env python3
"""Runs tests/present/outline-block.fs (the proof outline on inductive blocks
fed from an export; review rvI21 R4-5 and R4-6) and checks what it prints:
the empty block's statement line says there is no type ("Type:      none"),
and the use of a generated recursor is recalled as generated by Lean's kernel,
never as an earlier declaration. Needs GFORTH. Test-only."""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EXPECTED = [
    "Declaration [anonymous]",
    "  Type:      none",
    "Recall IE.B.rec : ",
    "generated by Lean's kernel for an earlier inductive type.",
    "0 case(s) failed",
]


def main():
    gforth = os.environ.get("GFORTH", "gforth")
    run = subprocess.run([gforth, "tests/present/outline-block.fs"], cwd=ROOT,
                         stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=300)
    missing = [text for text in EXPECTED if text not in run.stdout]
    if run.returncode != 0 or missing:
        sys.stdout.write(run.stdout + run.stderr)
        print(f"outline-block: exit {run.returncode}, missing {missing}")
        return 1
    print(f"outline-block: {len(EXPECTED)} of {len(EXPECTED)} expected lines printed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
