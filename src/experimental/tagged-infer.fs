\ Untrusted inference for a limited symbolic-universe fragment: Sort, bound
\ variables, Pi, lambda and a conservative application fragment. Applications
\ require a directly visible Pi and syntactically matching argument type;
\ constants and unsupported forms return unknown. This is NOT a
\ theorem checker or a trusted kernel. Load the term, level, scope, tagged
\ representation, session, handle, tagged-shift, tagged-instantiate and
\ tagged-compare modules first. Mutable arenas, no raw
\ writes, suffix-only rollback and single-threaded execution are assumptions.

0 constant lf-tinfer-ok
1 constant lf-tinfer-invalid
2 constant lf-tinfer-exhausted
3 constant lf-tinfer-unknown
6 constant lf-tinfer-frame-cells
create lf-tinfer-frames lf-term-capacity lf-tinfer-frame-cells * cells allot
variable lf-tinfer-depth
variable lf-tinfer-fuel
variable lf-tinfer-term-start
variable lf-tinfer-level-start
variable lf-tinfer-context-depth
create lf-tinfer-context lf-term-capacity cells allot

\ Access fields of the active bounded recursion frame.
: lf-tinfer-frame ( depth -- addr )
  lf-tinfer-frame-cells * cells lf-tinfer-frames + ;
: lf-tinfer-current ( -- addr ) lf-tinfer-depth @ 1- lf-tinfer-frame ;
: lf-tinfer@ ( offset -- value ) cells lf-tinfer-current + @ ;
: lf-tinfer! ( value offset -- ) cells lf-tinfer-current + ! ;
: lf-tinfer-leave ( result status -- result status ) -1 lf-tinfer-depth +! ;

\ Save a binder domain in the preceding context. Remove it after the body,
\ including when inference fails; the stack has a fixed finite capacity.
: lf-tinfer-push ( domain -- flag )
  lf-tinfer-context-depth @ lf-term-capacity >= if drop false exit then
  lf-tinfer-context-depth @ cells lf-tinfer-context + !
  1 lf-tinfer-context-depth +! true ;
: lf-tinfer-pop ( -- ) -1 lf-tinfer-context-depth +! ;

\ Shift a binder's stored type into the current context. Validation, shifting
\ and the outer inference consume one shared remaining visit budget.
: lf-tinfer-shift ( node amount -- result status )
  >r dup lf-term-identity 0= if r> drop drop -1 lf-tinfer-invalid exit then
  0 r> lf-tinfer-fuel @ lf-tagged-shift
  lf-tshift-fuel @ lf-tinfer-fuel ! swap drop ;

\ Compare two inferred/declared types using the conservative syntax test.
\ Both graphs are validated and compared with the remaining shared budget.
: lf-tinfer-compare ( left right -- status )
  dup lf-term-identity 0= if 2drop lf-tinfer-invalid exit then >r
  swap dup lf-term-identity 0= if 2drop r> drop lf-tinfer-invalid exit then
  rot r> lf-tinfer-fuel @ lf-tagged-compare
  lf-tcompare-fuel @ lf-tinfer-fuel ! ;

\ Substitute the original argument into a Pi body after conversion succeeds.
: lf-tinfer-instantiate ( body argument -- result status )
  dup lf-term-identity 0= if 2drop -1 lf-tinfer-invalid exit then >r
  swap dup lf-term-identity 0= if 2drop r> drop -1 lf-tinfer-invalid exit then
  rot r> lf-tinfer-fuel @ lf-tagged-instantiate
  lf-tinst-fuel @ lf-tinfer-fuel ! swap drop ;

\ Make a stamped symbolic Sort from an allocated level. An allocator failure
\ is reported as exhaustion and cannot yield an inferred type.
: lf-tinfer-sort ( level -- node status )
  dup lf-level-identity 0= if drop -1 lf-tinfer-invalid exit then
  lf-hterm-sort if drop lf-tinfer-ok else -1 lf-tinfer-exhausted then ;

\ Extract the level from an inferred Sort. An unsupported inferred type is
\ unknown, not a successful judgment or proof of inequality.
: lf-tinfer-sort-level ( node -- level status )
  lf-term-read 0= if -1 lf-tinfer-invalid exit then
  drop swap lf-tag-symbolic-sort <> if drop -1 lf-tinfer-unknown exit then
  lf-tinfer-ok ;

\ Infer an input node, charging one fuel unit per visit. Nodes generated by
\ this operation are output data, never interpreted as fresh source nodes.
: lf-tinfer-walk ( node -- type status )
  lf-tinfer-fuel @ 0= lf-tinfer-depth @ lf-term-capacity >= or if
    drop -1 lf-tinfer-exhausted exit
  then
  -1 lf-tinfer-fuel +!
  lf-tinfer-depth @ lf-tinfer-frame ! 1 lf-tinfer-depth +!
  0 lf-tinfer@ dup 0< swap lf-tinfer-term-start @ >= or if
    -1 lf-tinfer-invalid lf-tinfer-leave exit
  then
  0 lf-tinfer@ lf-term-read 0= if -1 lf-tinfer-invalid lf-tinfer-leave exit then
  3 lf-tinfer! 2 lf-tinfer! 1 lf-tinfer!
  1 lf-tinfer@ lf-tag-symbolic-sort = if
    2 lf-tinfer@ lf-level-succ 0= if
      -1 lf-tinfer-exhausted lf-tinfer-leave exit
    then
    lf-tinfer-sort lf-tinfer-leave exit
  then
  1 lf-tinfer@ lf-tag-bvar = if
    2 lf-tinfer@ lf-tinfer-context-depth @ >= if
      -1 lf-tinfer-invalid lf-tinfer-leave exit
    then
    lf-tinfer-context-depth @ 1- 2 lf-tinfer@ - cells lf-tinfer-context + @
    2 lf-tinfer@ 1+ lf-tinfer-shift lf-tinfer-leave exit
  then
  1 lf-tinfer@ lf-tag-app = if
    2 lf-tinfer@ recurse dup if lf-tinfer-leave exit then drop
    lf-term-read 0= if -1 lf-tinfer-invalid lf-tinfer-leave exit then
    5 lf-tinfer! 4 lf-tinfer!
    lf-tag-pi <> if -1 lf-tinfer-unknown lf-tinfer-leave exit then
    3 lf-tinfer@ recurse dup if lf-tinfer-leave exit then drop
    4 lf-tinfer@ lf-tinfer-compare
    ?dup if -1 swap lf-tinfer-leave exit then
    5 lf-tinfer@ 3 lf-tinfer@ lf-tinfer-instantiate lf-tinfer-leave exit
  then
  1 lf-tinfer@ lf-tag-pi = 1 lf-tinfer@ lf-tag-lam = or if
    2 lf-tinfer@ recurse dup if lf-tinfer-leave exit then drop
    lf-tinfer-sort-level dup if lf-tinfer-leave exit then drop 4 lf-tinfer!
    2 lf-tinfer@ lf-tinfer-push 0= if
      -1 lf-tinfer-exhausted lf-tinfer-leave exit
    then
    3 lf-tinfer@ recurse lf-tinfer-pop
    dup if lf-tinfer-leave exit then drop
    1 lf-tinfer@ lf-tag-lam = if
      2 lf-tinfer@ swap lf-term-pi if
        lf-tinfer-ok else -1 lf-tinfer-exhausted then
      lf-tinfer-leave exit
    then
    lf-tinfer-sort-level dup if lf-tinfer-leave exit then drop
    dup 0= if drop 0 else
      4 lf-tinfer@ swap lf-level-imax 0= if
        -1 lf-tinfer-exhausted lf-tinfer-leave exit
      then
    then
    lf-tinfer-sort lf-tinfer-leave exit
  then
  -1 lf-tinfer-unknown lf-tinfer-leave ;

\ Validate the handle, all reachable tags/levels and cross-arena identities;
\ then infer with the remaining budget. Any failure restores both allocation
\ counts, but allocation identities do not roll back. Success retains temporary
\ nodes and returns (index identity ok); failure returns (-1 0 status).
: lf-tinfer ( root identity fuel -- type identity status )
  >r 2dup r> lf-hterm-check ?dup if
    >r 2drop -1 0 r> exit
  then
  drop lf-href-fuel @ lf-tinfer-fuel !
  lf-term-count @ lf-tinfer-term-start !
  lf-level-count @ lf-tinfer-level-start !
  0 lf-tinfer-depth ! 0 lf-tinfer-context-depth ! lf-tinfer-walk
  dup if
    >r drop lf-tinfer-term-start @ lf-term-count !
    lf-tinfer-level-start @ lf-level-count ! -1 0 r> exit
  then
  drop dup lf-term-identity 0= if
    drop lf-tinfer-term-start @ lf-term-count !
    lf-tinfer-level-start @ lf-level-count ! -1 0 lf-tinfer-invalid exit
  then
  lf-tinfer-ok ;
