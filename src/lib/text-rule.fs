\ Whether code lies in one of the n ranges of table.
: tr-range ( table k -- lo hi ) 2* cells + dup @ swap cell+ @ ;
: tr-among? ( code table n -- flag )
  0 ?do 2dup i tr-range between? if 2drop true unloop exit then loop 2drop false ;
\ A code of -1 stands for bytes that are not UTF-8: banned, and not seen.
: tr-banned? ( code -- flag )
  dup 0< if drop true exit then tr-banned tr-banned# tr-among? ;
: tr-seen? ( code -- flag )
  dup 0< if drop false exit then tr-unseen tr-unseen# tr-among? 0= ;

\ Decoding: the code point of the n-byte character at c-addr, from the
\ lead byte's low bits and six bits of each byte after it. n is the
\ length utf8-length gave, at least 1.
: tr-mask ( n -- mask )
  case 1 of $7f endof 2 of $1f endof 3 of $0f endof $07 swap endcase ;
: tr-lead ( c-addr n -- bits ) swap c@ swap tr-mask and ;
: tr-tail ( code c-addr -- code' ) c@ $3f and swap 6 lshift or ;
: tr-decode ( c-addr n -- code )
  2dup tr-lead -rot chars over + swap char+ ?do i tr-tail loop ;
\ The first character of c-addr u and the rest; at bytes that do not
\ begin a valid character, all of them, as the code -1.
: tr-next ( c-addr u -- c-addr' u' code )
  2dup utf8-length ?dup 0= if + 0 -1 exit then
  >r over r@ tr-decode -rot r> /string rot ;
\ Whether xt ( code -- flag ) holds for some character of c-addr u.
: tr-some? ( c-addr u xt -- flag )
  >r begin dup while tr-next r@ execute if 2drop r> drop true exit then repeat
  2drop r> drop false ;

