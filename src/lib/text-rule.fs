\ Visible text: whether a UTF-8 text shows what it says. A standalone
\ library for any Forth-2012 system with 8-bit characters; it needs
\ bounds.fs, bytes.fs (UTF-8 framing) and module.fs (ADR 0010).
\
\   s" composition" tr-shown?            \ true
\   s\" a\xe2\x80\xaeb" tr-rule?         \ false: U+202E, a bidirectional control
\   s\" \xe3\x85\xa4" tr-shown?           \ false: U+3164 HANGUL FILLER alone
\   s\" a\xcc\x81" tr-shown?             \ true: a, then a combining acute accent
\
\ tr-rule? ( c-addr u -- flag ): the text keeps the rule. It is valid
\ UTF-8 (bytes.fs's utf8-valid?: no overlong form, no surrogate, nothing
\ past U+10FFFF) and holds no control character (Unicode Cc), no format
\ character (Cf: bidirectional controls, zero-width characters, tags), no
\ line or paragraph separator (Zl, Zp) and no surrogate (Cs). So it shows
\ what it says, and it cannot start a new line. The empty text keeps it.
\ tr-shown? ( c-addr u -- flag ): the text keeps the rule and has a
\ character that is seen, that is not a space (Zs), not a blank-looking
\ filler (U+115F, U+1160, U+2800, U+3164, U+FFA0), not a combining mark
\ (M) and not a default-ignorable code point. So an empty or blank text,
\ or one of marks or ignorable characters alone, is not shown. Characters
\ of private use (Co) and code points not yet assigned (Cn), such as
\ U+E000 or U+FFFF, count as seen, though many fonts draw them blank:
\ which code points are assigned changes with every Unicode version.
\ Categories are those of Unicode 15.1 (15.0 has the same).
\
\ This is the rule the owner approved for program receipts 0.2
\ (docs/programming/PROGRAM_RECEIPTS.md), which LeanForth's run records
\ follow (docs/programming/RUN_RECORDS.md, the schema's "text" and
\ "shown" patterns); nothing in it is LeanForth's. The two tables are
\ generated by scripts/text_rule_tables.py from Python's Unicode data, and
\ tests/core/test_run_records.py checks them against it and against the
\ schema; tests/lib/text-rule.fs tests the words on their own.
\ Interface: tr-rule? tr-shown?; every other word is private (lf-lib-private).
\ State: none; the tables are constant after loading. Untrusted. It reads
\ bytes (c@) to decode UTF-8. The file loads in decimal whatever BASE is,
\ then restores it.

